    'darkBg3': c['color8'], 'darkBgDim': c['color0'],
    'darkFg0': s['foreground'], 'darkFg1': s['foreground'], 'darkFgWarm': s['foreground'],
    'darkGray': c['color8'], 'darkGray0': c['color8'], 'darkGray2': c['color7'],
    'darkRed': c['color1'], 'darkGreen': c['color2'], 'darkYellow': c['color3'],
    'darkBlue': c['color4'], 'darkPurple': c['color5'], 'darkAqua': c['color6'],
    'darkOrange': c['color3'],
    'darkRedBright': c['color9'], 'darkGreenBright': c['color10'],
    'darkYellowBright': c['color11'], 'darkBlueBright': c['color12'],
    'darkPurpleBright': c['color13'], 'darkAquaBright': c['color14'],
    'darkOrangeBright': c['color11'],
    'darkDiffAddedBg': c['color0'], 'darkDiffRemovedBg': c['color0'],
    'darkDiffAddedLnBg': c['color0'], 'darkDiffRemovedLnBg': c['color0'],
    'darkDiffLn': c['color8'],
}
for k in list(defs):
    if k.startswith('dark'):
        defs['light' + k[4:]] = defs[k]
roles = {
    'primary': ('darkBlueBright', 'lightBlueBright'),
    'secondary': ('darkPurpleBright', 'lightPurpleBright'),
    'accent': ('darkAquaBright', 'lightAquaBright'),
    'error': ('darkRedBright', 'lightRedBright'),
    'warning': ('darkOrangeBright', 'lightOrangeBright'),
    'success': ('darkGreenBright', 'lightGreenBright'),
    'info': ('darkYellowBright', 'lightYellowBright'),
    'text': ('darkFg1', 'lightFg1'),
    'textMuted': ('darkGray', 'lightGray'),
    'background': ('darkBg0', 'lightBg0'),
    'backgroundPanel': ('darkBg1', 'lightBg1'),
    'backgroundElement': ('darkBg2', 'lightBg2'),
    'border': ('darkBg3', 'lightBg3'),
    'borderActive': ('darkFg1', 'lightFg1'),
    'borderSubtle': ('darkBg2', 'lightBg2'),
    'diffAdded': ('darkGreen', 'lightGreen'),
    'diffRemoved': ('darkRed', 'lightRed'),
    'diffContext': ('darkGray', 'lightGray'),
    'diffHunkHeader': ('darkAqua', 'lightAqua'),
    'diffHighlightAdded': ('darkGreenBright', 'lightGreenBright'),
    'diffHighlightRemoved': ('darkRedBright', 'lightRedBright'),
    'diffAddedBg': ('darkDiffAddedBg', 'lightDiffAddedBg'),
    'diffRemovedBg': ('darkDiffRemovedBg', 'lightDiffRemovedBg'),
    'diffContextBg': ('darkBg1', 'lightBg1'),
    'diffLineNumber': ('darkGray', 'lightGray'),
    'diffAddedLineNumberBg': ('darkDiffAddedLnBg', 'lightDiffAddedLnBg'),
    'diffRemovedLineNumberBg': ('darkDiffRemovedLnBg', 'lightDiffRemovedLnBg'),
    'markdownText': ('darkFg1', 'lightFg1'),
    'markdownHeading': ('darkBlueBright', 'lightBlueBright'),
    'markdownLink': ('darkAquaBright', 'lightAquaBright'),
    'markdownLinkText': ('darkGreenBright', 'lightGreenBright'),
    'markdownCode': ('darkYellowBright', 'lightYellowBright'),
    'markdownBlockQuote': ('darkGray', 'lightGray'),
    'markdownEmph': ('darkPurpleBright', 'lightPurpleBright'),
    'markdownStrong': ('darkOrangeBright', 'lightOrangeBright'),
    'markdownHorizontalRule': ('darkGray', 'lightGray'),
    'markdownListItem': ('darkBlueBright', 'lightBlueBright'),
    'markdownListEnumeration': ('darkAquaBright', 'lightAquaBright'),
    'markdownImage': ('darkAquaBright', 'lightAquaBright'),
    'markdownImageText': ('darkGreenBright', 'lightGreenBright'),
    'markdownCodeBlock': ('darkFg1', 'lightFg1'),
    'syntaxComment': ('darkGray', 'lightGray'),
    'syntaxKeyword': ('darkRedBright', 'lightRedBright'),
    'syntaxFunction': ('darkGreenBright', 'lightGreenBright'),
    'syntaxVariable': ('darkBlueBright', 'lightBlueBright'),
    'syntaxString': ('darkYellowBright', 'lightYellowBright'),
    'syntaxNumber': ('darkPurpleBright', 'lightPurpleBright'),
    'syntaxType': ('darkAquaBright', 'lightAquaBright'),
    'syntaxOperator': ('darkOrangeBright', 'lightOrangeBright'),
    'syntaxPunctuation': ('darkFg1', 'lightFg1'),
}
theme = {k: {'dark': d, 'light': l} for k, (d, l) in roles.items()}
json.dump({'$schema': 'https://opencode.ai/theme.json', 'defs': defs, 'theme': theme},
          open(sys.argv[2], 'w'), indent=2)
EOF

# Ask a running vxwm to re-read xrdb (its Alt+F5 -> xrdb bind).
# Needs xdotool; XTEST events trip root-window grabs regardless of focus.
# Depends on MODKEY=Alt and the Mod+F5 bind in vxwm's config.h.
if command -v xdotool >/dev/null 2>&1; then
    sleep 0.2
    xdotool key Alt+F5
fi

# Push the new colors to the browser via pywalfox. Fire-and-forget over
# its unix socket: silent no-op when LibreWolf isn't running.
if command -v pywalfox >/dev/null 2>&1; then
    pywalfox update
fi
