#!/bin/sh
# wal-st: run pywal, then preserve st's 40m tweak under the new theme.
#
# In this st build SGR 40m paints palette index 0, which is customized to a
# visible surface color instead of black (the fish prompt uses
# `set_color -b black` for the pwd segment background, plus black fg for
# the box lines). Pinning index 0 to the terminal background would make
# those invisible, so we pin it to pywal's color8 (bright black), the
# palette's surface analog:
#   st.color0      -> pywal color8 (tight binding beats pywal's loose
#                   "*.color0" for st's lookup, other apps are unaffected)
#   st.cursorColor -> pywal cursor   (pywal sets no cursor color st matches)
# via xrdb for future st windows, plus OSC 4/12 for the calling terminal
# (other existing windows pick it up on restart).
#
# Tabbed uses bespoke resource names (tabbed.normbgcolor etc.) that pywal
# never emits, so map them explicitly the same way. The selected tab shares
# its background with the wm's focused border / selected tag: both read
# pywal color8, the wm via its dwm.selbgcolor/dwm.selbordercolor xrdb keys
# (picked up on Alt+F5 below), tabbed via tabbed.selbgcolor. Inactive window
# borders use a background->color8 blend (dwm.normbordercolor) so they stay
# visible instead of vanishing into the background; this requires the
# vxwm-xrdb-per-role.patch applied by the vxwm PKGBUILD. The legacy
# dwm.color6 key is still set for unpatched builds (there it also recolors
# bar text, hence the dim bar).
#
# Usage: wal-st -i ~/wallpaper.png [any other wal args]

wal "$@"
ret=$?
[ "$ret" -ne 0 ] && exit "$ret"

json="$HOME/.cache/wal/colors.json"
[ -f "$json" ] || { echo "wal-st: $json not found" >&2; exit 1; }

surface=$(python3 -c "import json,sys; print(json.load(open(sys.argv[1]))['colors']['color8'])" "$json") || exit 1
cursor=$(python3 -c "import json,sys; print(json.load(open(sys.argv[1]))['special']['cursor'])" "$json") || exit 1

# TODO: this needs to be sent to all terminals
# { echo "st.color0: $surface"; echo "st.cursorColor: $cursor"; } | xrdb -merge
# printf '\033]4;0;%s\007\033]12;%s\007' "$surface" "$cursor"
# wow this was dumb. `set_color brblack` instead of `set_color black` fixes the issue

# tabbed (see header): background/foreground/urgent follow pywal, selected
# shares color8 with the wm's focused border + selected tag. vxwm per-role
# keys (patched xrdb): bar text follows pywal, inactive border is a
# background->color8 blend so it reads as a visible edge.
tbg=$(python3 -c "import json,sys; print(json.load(open(sys.argv[1]))['special']['background'])" "$json") || exit 1
tfg=$(python3 -c "import json,sys; print(json.load(open(sys.argv[1]))['special']['foreground'])" "$json") || exit 1
turg=$(python3 -c "import json,sys; print(json.load(open(sys.argv[1]))['colors']['color1'])" "$json") || exit 1
nbrd=$(python3 -c "
import sys
def rgb(h): return [int(h[i:i+2], 16) for i in (1, 3, 5)]
a, b = rgb(sys.argv[1]), rgb(sys.argv[2])
print('#%02x%02x%02x' % tuple((x + y) // 2 for x, y in zip(a, b)))
" "$tbg" "$surface") || exit 1
{ echo "st.color0: $surface"; echo "st.cursorColor: $cursor";
  echo "dwm.color6: $surface";
  echo "dwm.normbgcolor: $tbg"; echo "dwm.normfgcolor: $tfg";
  echo "dwm.normbordercolor: $nbrd";
  echo "dwm.selbgcolor: $surface"; echo "dwm.selfgcolor: $tfg";
  echo "dwm.selbordercolor: $surface";
  echo "tabbed.normbgcolor: $tbg"; echo "tabbed.normfgcolor: $tfg";
  echo "tabbed.selbgcolor: $surface"; echo "tabbed.selfgcolor: $tfg";
  echo "tabbed.urgbgcolor: $turg"; echo "tabbed.urgfgcolor: $tfg"; } | xrdb -merge

# Render dunst config from the pywal palette: frame width matches the wm
# borderpx (3), transparency 5 tracks the 95% opacity used for st/dmenu/
# tabbed, frame follows the color8 surface. dunst picks it up via reload.
mkdir -p "$HOME/.config/dunst"
python3 - "$json" "$HOME/.config/dunst/dunstrc" <<'EOF' || exit 1
import json, sys
wal = json.load(open(sys.argv[1]))
c, s = wal['colors'], wal['special']
bg, fg, sf, red, bred = s['background'], s['foreground'], c['color8'], c['color1'], c['color9']
open(sys.argv[2], 'w').write(
"""# Generated by wal-st from the pywal palette. Do not hand-edit:
# re-run wal-st (or change wallpaper) to regenerate.
[global]
    font = JetBrainsMono Nerd Font 10
    frame_width = 2
    transparency = 5
    idle_threshold = 120
    show_indicators = false
    separator_height = 2
    padding = 8
    horizontal_padding = 8

[urgency_low]
    background = "%s"
    foreground = "%s"
    frame_color = "%s"
    timeout = 5

[urgency_normal]
    background = "%s"
    foreground = "%s"
    frame_color = "%s"
    timeout = 10

[urgency_critical]
    background = "%s"
    foreground = "%s"
    frame_color = "%s"
    timeout = 0
""" % (bg, fg, sf, bg, fg, sf, red, fg, bred))
EOF
if command -v dunstctl >/dev/null 2>&1; then
    dunstctl reload >/dev/null 2>&1
fi

# Render an opencode theme from the pywal palette (same role names as
# gruvbox-material-custom.json; light roles reuse the single pywal palette).
# Select it once via /theme -> pywal; re-select after each wallpaper change
# (opencode only loads theme files on select/startup).
mkdir -p "$HOME/.config/opencode/themes"
python3 - "$json" "$HOME/.config/opencode/themes/pywal.json" <<'EOF' || exit 1
